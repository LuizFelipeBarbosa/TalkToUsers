import { createClient } from "@base44/sdk";
const base44 = createClient({ appId: "6acac1d3560f9955c41aa9b4", serverUrl: "https://base44.app", requiresAuth: false });
const g = (await base44.functions.invoke("graphData", { action: "load" })).data;
const fmt = (n) => (n == null ? "-" : n >= 1e12 ? `$${(n / 1e12).toFixed(2)}T` : n >= 1e9 ? `$${(n / 1e9).toFixed(1)}B` : `$${(n / 1e6).toFixed(0)}M`);
const host = (u) => { try { return new URL(u).hostname.replace(/^www\./, ""); } catch { return ""; } };
const source = (c) => c.value_source || (c.origin === "seed" ? "seed" : c.value_usd ? "llm_estimate" : "none");
const cos = g.companies.filter((c) => c.kind !== "investor");
const count = cos.reduce((m, c) => ((m[source(c)] = (m[source(c)] || 0) + 1), m), {});
console.log(`Non-investor companies: ${cos.length}; value sources:`, count);
const today = new Date().toISOString().slice(0, 10);
const days = (d) => (Date.parse(today) - Date.parse(d.length === 4 ? `${d}-07-01` : d.length === 7 ? `${d}-15` : d)) / 864e5;
const line = (c) => `${c.name.padEnd(26).slice(0, 26)} ${fmt(c.value_usd).padEnd(9)} ${source(c).padEnd(12)} ${(c.value_basis || "").padEnd(13)} ${(c.value_as_of || "").padEnd(10)} ${host(c.value_source_url || "")}${c.seed_value_usd ? `  (curated was ${fmt(c.seed_value_usd)})` : ""}`;
const holdings = new Set(g.holdings.map((h) => h.company));
console.log("\nPortfolio holdings:");
for (const c of cos.filter((c) => holdings.has(c.key))) console.log("  " + line(c));
console.log("\nLargest 20 by value:");
for (const c of cos.slice().sort((a, b) => (b.value_usd || 0) - (a.value_usd || 0)).slice(0, 20)) console.log("  " + line(c));
const grounded = cos.filter((c) => c.value_source === "article");
const staleCap = grounded.filter((c) => c.value_basis === "market_cap" && days(c.value_as_of) > 45);
const old = grounded.filter((c) => c.value_basis !== "market_cap" && days(c.value_as_of) > 548);
const curated = cos.filter((c) => source(c) === "seed");
console.log(`\nCheck: market caps older than 45 days: ${staleCap.map((c) => `${c.name} ${c.value_as_of}`).join(", ") || "none"}`);
console.log(`Check: grounded values older than 18 months: ${old.map((c) => `${c.name} ${c.value_as_of}`).join(", ") || "none"}`);
console.log(`Check: curated values not grounded: ${curated.map((c) => `${c.name} ${fmt(c.value_usd)}`).join(", ") || "none"}`);
console.log(`Check: cited hosts: ${Object.entries(grounded.reduce((m, c) => ((m[host(c.value_source_url)] = (m[host(c.value_source_url)] || 0) + 1), m), {})).sort((a, b) => b[1] - a[1]).map(([h, n]) => `${h} ${n}`).join(", ")}`);
